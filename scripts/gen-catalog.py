"""Builds supabase/seed.sql from supabase/gobear-models.txt (the vending machine's model list)."""
import re, pathlib
ROOT = pathlib.Path(__file__).resolve().parent.parent
BASE = "https://saas-1302732800.cos.accelerate.myqcloud.com/uploads/images/"
BRANDS = {"A": ("apple", "Apple"), "S": ("samsung", "Samsung"), "G": ("google", "Google"), "M": ("moto", "Moto")}
PRODUCT = {"1": ("m2", 3000), "2": ("m3", 2000)}

def nice(brand, raw):
    s = raw
    if brand == "A":
        s = re.sub(r"^iPhone(?=\d|Air)", "iPhone ", s)
    elif brand == "G":
        s = re.sub(r"^Pixel(?=\d)", "Pixel ", s)
    elif brand == "S":
        s = s.replace("(5G)", " 5G")
    elif brand == "M":
        s = re.sub(r"^edge(?=\d)", "edge ", s)
        s = re.sub(r"^g(play|power|stylus)\s*", r"g \1 ", s)
        s = re.sub(r"^g(?=\d)", "g ", s)
        s = "moto " + s if s.startswith("g") else "motorola " + s
    return re.sub(r"\s+", " ", s).strip()

def slug(s):
    return re.sub(r"[^a-z0-9]+", "-", s.lower().replace("+", " plus")).strip("-")

q = lambda s: "'" + s.replace("'", "''") + "'"
devices, variants = [], []
for i, line in enumerate((ROOT / "supabase/gobear-models.txt").read_text().strip().splitlines()):
    b, series, mid, raw, mats = line.split("|")
    bid, _ = BRANDS[b]
    name = nice(b, raw)
    did = slug(name)
    devices.append(f"({q(did)},{q(bid)},{q(name)},{q(series)},{i+1},{mid})")
    for m in mats.split(";"):
        mat, sku, path = m.split(",")
        pid, price = PRODUCT[mat]
        variants.append(f"({q(did)},{q(pid)},{price},100,{q(BASE + path + '.png')},{sku})")

sql = f"""-- PrintPhoneCover catalog: every phone model and case on the vending machine.
-- Generated by scripts/gen-catalog.py from supabase/gobear-models.txt. Safe to run more than once:
-- it adds new models and updates masks, and keeps the prices and stock you set in Admin.

-- Columns for machine masks (also in schema.sql for new installs)
alter table devices add column if not exists series text;
alter table devices add column if not exists source_model_id int;
alter table devices alter column geometry drop not null;
alter table variants add column if not exists mask_src text;
alter table variants add column if not exists mask_url text;
alter table variants add column if not exists mask_w int;
alter table variants add column if not exists mask_h int;
alter table variants add column if not exists source_sku_id int;

-- Old orders keep their details even if a model is removed later
alter table orders drop constraint if exists orders_variant_id_fkey;
alter table orders add constraint orders_variant_id_fkey foreign key (variant_id) references variants(id) on delete set null;

-- Public bucket for our own copies of the masks
insert into storage.buckets (id, name, public) values ('masks', 'masks', true)
on conflict (id) do update set public = true;

insert into brands (id, name, sort, active) values
  ('apple','Apple',1,true), ('samsung','Samsung',2,true), ('google','Google',3,true), ('moto','Moto',4,true)
on conflict (id) do update set active = true;

insert into products (id, code, name, description, finish, sort) values
  ('m2','M2','Skin-Touch Magnetic Case',
   'Soft, skin-friendly matte texture with strong magnets for MagSafe charging. Two interchangeable lens frames, precise speaker holes and built-in buttons.','solid',1),
  ('m3','M3','Clear Case',
   'Clear, scratch-resistant case. Your design prints right onto it, and any part you leave empty stays see-through.','clear',2)
on conflict (id) do update set code = excluded.code, name = excluded.name, description = excluded.description, finish = excluded.finish;

-- Remove the first hand-drawn test outlines (they are not machine masks)
delete from devices where source_model_id is null;

insert into devices (id, brand_id, name, series, sort, source_model_id) values
{",\n".join(devices)}
on conflict (id) do update set brand_id = excluded.brand_id, name = excluded.name, series = excluded.series,
  sort = excluded.sort, source_model_id = excluded.source_model_id;

insert into variants (device_id, product_id, price_cents, stock, mask_src, source_sku_id) values
{",\n".join(variants)}
on conflict (device_id, product_id) do update set
  mask_url = case when variants.mask_src is distinct from excluded.mask_src then null else variants.mask_url end,
  mask_w   = case when variants.mask_src is distinct from excluded.mask_src then null else variants.mask_w end,
  mask_h   = case when variants.mask_src is distinct from excluded.mask_src then null else variants.mask_h end,
  mask_src = excluded.mask_src, source_sku_id = excluded.source_sku_id;
"""
(ROOT / "supabase/seed.sql").write_text(sql)
print(len(devices), "models,", len(variants), "model+case combinations")
